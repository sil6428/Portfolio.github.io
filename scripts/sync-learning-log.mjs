import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectDirectory = path.resolve(scriptDirectory, "..");
const sourceDirectory = path.resolve(projectDirectory, "..", "learning-log", "entries");
const outputFile = path.join(projectDirectory, "app", "learning-log-data.generated.ts");

async function collectMarkdownFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? collectMarkdownFiles(target) : entry.name.endsWith(".md") ? [target] : [];
  }));
  return files.flat();
}

const markdownFiles = await collectMarkdownFiles(sourceDirectory);
const entries = await Promise.all(markdownFiles.map(async (file) => {
  const markdown = (await readFile(file, "utf8")).replace(/\r\n/g, "\n").trim();
  const [firstLine = "", ...remainingLines] = markdown.split("\n");
  const date = path.basename(file, ".md");
  const [year, month] = date.split("-");
  const title = firstLine.replace(/^#\s+/, "").replace(/^\d{4}-\d{2}-\d{2}\s+-\s+/, "").trim() || date;
  const monthLabel = new Intl.DateTimeFormat("en-CA", { month: "long", timeZone: "UTC" }).format(new Date(`${year}-${month}-01T00:00:00Z`));

  return {
    id: `learning-log-entry-${date}`,
    date,
    year,
    month,
    monthLabel,
    title,
    body: remainingLines.join("\n").trim(),
  };
}));

entries.sort((a, b) => b.date.localeCompare(a.date));

const source = `// Generated by scripts/sync-learning-log.mjs from the public learning-log repository.\n` +
  `// Edit the source Markdown entries, then run npm run sync:learning-log.\n\n` +
  `export type LearningLogEntry = {\n` +
  `  id: \`learning-log-entry-\${string}\`;\n` +
  `  date: string;\n` +
  `  year: string;\n` +
  `  month: string;\n` +
  `  monthLabel: string;\n` +
  `  title: string;\n` +
  `  body: string;\n` +
  `};\n\n` +
  `export const learningLogEntries = ${JSON.stringify(entries, null, 2)} as const satisfies readonly LearningLogEntry[];\n`;

await writeFile(outputFile, source, "utf8");
console.log(`Synced ${entries.length} learning-log entries to ${path.relative(projectDirectory, outputFile)}.`);
